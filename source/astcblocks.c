uint32_t AstcFnv1a(const void *data, uint32_t size) {
    const uint8_t *const bytes = (const uint8_t *)data;
    uint32_t hash = 0x811C9DC5u;
    for (uint32_t i = 0; i < size; ++i) {
        hash = (hash ^ bytes[i]) * 0x01000193u;
    }
    return hash;
}
