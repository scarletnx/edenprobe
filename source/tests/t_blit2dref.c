static uint8_t source[BLIT2D_SRC_BYTES];
static uint8_t image[BLIT2D_DST_BYTES];

static void CheckSource(void) {
    char got_source[33], got_fill[33];
    Blit2dFillSource(source);
    Blit2dMd5Hex(source, sizeof(source), got_source);
    memset(image, BLIT2D_FILL, sizeof(image));
    Blit2dMd5Hex(image, sizeof(image), got_fill);
    CHECK_TRUE(SUITE, "blit2d: the source and the filled destination are the script's",
               CHECK_NONE,
               strcmp(got_source, PINNED_SOURCE) == 0 && strcmp(got_fill, PINNED_UNTOUCHED) == 0,
               "source %s, the script %s; filled %s, the script %s", got_source, PINNED_SOURCE,
               got_fill, PINNED_UNTOUCHED);
}

static void CheckImages(void) {
    uint32_t wrong = 0;
    char first[160] = "";
    const bool shape = sizeof(PINNED) / sizeof(PINNED[0]) == BLIT2D_CASES;
    for (uint32_t i = 0; shape && i < BLIT2D_CASES; ++i) {
        const Blit2dCase *const c = Blit2dCaseAt((Blit2dCaseId)i);
        for (uint32_t k = 0; k < BLIT2D_COMBINATIONS; ++k) {
            char got[33];
            Blit2dExpected(c, k, image);
            Blit2dMd5Hex(image, sizeof(image), got);
            if ((strcmp(got, PINNED[i].md5[k]) != 0 || strcmp(c->name, PINNED[i].name) != 0) &&
                wrong++ == 0u) {
                snprintf(first, sizeof(first), "%s answers %u: %s, the script %s %s", c->name,
                         (unsigned)k, got, PINNED[i].name, PINNED[i].md5[k]);
            }
        }
    }
    CHECK_TRUE(SUITE, "blit2d: every case under every answer is the image the script works out",
               CHECK_NONE, shape && wrong == 0u, "%u of %u images differ; first %s",
               (unsigned)wrong, (unsigned)(BLIT2D_CASES * BLIT2D_COMBINATIONS), first);
}

static void CheckWords(void) {
    uint32_t words[BLIT2D_WORDS];
    const size_t count = Blit2dRawWords(Blit2dCaseAt(BLIT2D_CORNER_2_3), PINNED_FAKE_SRC,
                                        PINNED_FAKE_DST, words);
    const size_t want = sizeof(PINNED_WORDS_CORNER_2_3) / sizeof(PINNED_WORDS_CORNER_2_3[0]);
    size_t at = 0;
    while (at < count && at < want && words[at] == PINNED_WORDS_CORNER_2_3[at]) {
        ++at;
    }
    CHECK_TRUE(SUITE, "blit2d: the 2D engine's words are the script's, from NVIDIA's offsets",
               CHECK_NONE, count == want && at == want,
               "%u words, the script %u; the first difference at word %u: 0x%08x, the script "
               "0x%08x",
               (unsigned)count, (unsigned)want, (unsigned)at,
               (unsigned)(at < count ? words[at] : 0u),
               (unsigned)(at < want ? PINNED_WORDS_CORNER_2_3[at] : 0u));
}

void RunReferenceBlit2d(void) {
    CheckSource();
    CheckImages();
    CheckWords();
}
