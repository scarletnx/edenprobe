// The blit2d suite's model, held to tools/blit2d-expect.py, which works the same images out with
// no code in common: there a gob is a permutation of address bits and the rules are exact
// fractions, here CohBlockLinearOffset and 32.32 steps. Every case under every combination of
// answers, the source, the untouched destination and the command words, by MD5 or word by word.

