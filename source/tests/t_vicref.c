static uint8_t Byte(int32_t ten, uint16_t low, uint16_t high) {
    const int32_t c = ten < low ? low : ten > high ? high : ten;
    return (uint8_t)(c >> 2);
}

static void CheckMatrix(void) {
    // The table the case was asked with: YUV in, R, G and B truncated, then with 128 added
    // before the shift.
    static const uint8_t TABLE[6][9] = {
        {235, 128, 128, 254, 254, 254, 255, 255, 255},
        {16, 128, 128, 0, 0, 0, 0, 0, 0},
        {126, 128, 128, 128, 128, 128, 128, 128, 128},
        {81, 90, 240, 254, 0, 0, 254, 0, 0},
        {145, 54, 34, 0, 255, 1, 0, 255, 1},
        {41, 240, 110, 0, 0, 254, 0, 0, 254},
    };
    const VicCase *const c = VicCaseAt(4);
    uint32_t wrong = 0;
    char first[96] = "";
    for (uint32_t i = 0; i < 6u; ++i) {
        for (uint32_t rounding = 0; rounding < 2u; ++rounding) {
            for (uint32_t row = 0; row < 3u; ++row) {
                const int32_t ten = VicMatrixChannel(
                    c->jobs[i].slots[0].m, row, TABLE[i][0] << 2, TABLE[i][1] << 2,
                    TABLE[i][2] << 2, 0u, false, rounding != 0u);
                const uint8_t got = Byte(ten, 0u, 1023u);
                const uint8_t want = TABLE[i][3u + rounding * 3u + row];
                if (got != want && wrong++ == 0u) {
                    snprintf(first, sizeof(first), "YUV %u %u %u channel %u: %u, the table %u",
                             TABLE[i][0], TABLE[i][1], TABLE[i][2], (unsigned)row, got, want);
                }
            }
        }
    }
    CHECK_TRUE(SUITE, "vic: the BT.601 colours, truncated and rounded, are the table asked for",
               CHECK_NONE, wrong == 0u && strcmp(c->name, "vic_matrix_601") == 0,
               "%u of 36 channels differ; first %s", (unsigned)wrong, first);

    const VicCase *const shift = VicCaseAt(5);
    uint8_t before[3], after[3];
    for (uint32_t row = 0; row < 3u; ++row) {
        before[row] = Byte(VicMatrixChannel(shift->jobs[0].slots[0].m, row, 126 << 2, 128 << 2,
                                            128 << 2, 2u, false, false),
                           0u, 1023u);
        after[row] = Byte(VicMatrixChannel(shift->jobs[0].slots[0].m, row, 126 << 2, 128 << 2,
                                           128 << 2, 2u, true, false),
                          0u, 1023u);
    }
    CHECK_TRUE(SUITE, "vic: the shift before the constant gives 128s, after it 255, 26, 255",
               CHECK_NONE,
               before[0] == 128u && before[1] == 128u && before[2] == 128u && after[0] == 255u &&
                   after[1] == 26u && after[2] == 255u,
               "before %u %u %u, after %u %u %u", before[0], before[1], before[2], after[0],
               after[1], after[2]);

    // White and black through the matrix land past 64..940 and the clamp brings them back.
    const VicCase *const clamp = VicCaseAt(6);
    uint8_t got[2][3];
    for (uint32_t j = 0; j < 2u; ++j) {
        const VicSlot *const s = &clamp->jobs[j].slots[0];
        for (uint32_t row = 0; row < 3u; ++row) {
            got[j][row] = Byte(VicMatrixChannel(s->m, row, s->image.y << 2, s->image.u << 2,
                                                s->image.v << 2, 0u, false, false),
                               s->clamp_low, s->clamp_high);
        }
    }
    CHECK_TRUE(SUITE, "vic: the soft clamp at 64..940 holds white at 235 and black at 16",
               CHECK_NONE,
               got[0][0] == 235u && got[0][1] == 235u && got[0][2] == 235u && got[1][0] == 16u &&
                   got[1][1] == 16u && got[1][2] == 16u,
               "white %u %u %u, black %u %u %u", got[0][0], got[0][1], got[0][2], got[1][0],
               got[1][1], got[1][2]);
}

/// The little-endian word of @p size bytes at @p offset in the packed structure.
static uint64_t Word(uint32_t offset, uint32_t size) {
    uint64_t value = 0;
    for (uint32_t i = 0; i < size; ++i) {
        value |= (uint64_t)config[offset + i] << (8u * i);
    }
    return value;
}

static void CheckStructure(void) {
    // The passthrough job's words worked out by hand from vic40.h's bit positions.
    static const struct {
        uint32_t offset, size;
        uint64_t value;
        const char *what;
    } WORDS[] = {
        {0x000, 8, 0x40004u, "downsample 1.0 both ways"},
        {0x010, 8, 0x0u, "alpha fill Opaque, background nought"},
        {0x018, 4, 0xf0000u, "target left 0, right 15"},
        {0x01c, 4, 0xf0000u, "target top 0, bottom 15"},
        {0x020, 4, 0x1fu, "output A8B8G8R8, pitch"},
        {0x024, 4, 0x3c00fu, "output surface 16 by 16"},
        {0x028, 4, 0x3c0ffu, "output luma 256 by 16"},
        {0x02c, 4, 0xfffffffu, "output chroma 16383, unused"},
        {0x090, 8, 0x101u, "slot 0 enabled, current field"},
        {0x0a0, 8, 0x7ff000ffc00u, "clamp 0..1023, planar alpha 1023, constant alpha"},
        {0x0b0, 8, 0xf000000000000u, "source left 0, right 15 in 16.16"},
        {0x0b8, 8, 0xf000000000000u, "source top 0, bottom 15 in 16.16"},
        {0x0c0, 8, 0xf0000000f0000u, "destination 0..15 both ways"},
        {0x0d0, 4, 0x100044u, "slot format 68, cache width 64Bx4"},
        {0x0d4, 4, 0x3c00fu, "slot surface 16 by 16"},
        {0x0d8, 4, 0x3c0ffu, "slot luma 256 by 16"},
        {0x0dc, 4, 0x1c07fu, "slot chroma 128 pairs by 8"},
    };
    VicPack(&VicCaseAt(0)->jobs[0], config);
    uint32_t wrong = 0;
    char first[128] = "";
    for (size_t i = 0; i < sizeof(WORDS) / sizeof(WORDS[0]); ++i) {
        const uint64_t got = Word(WORDS[i].offset, WORDS[i].size);
        if (got != WORDS[i].value && wrong++ == 0u) {
            snprintf(first, sizeof(first), "0x%03x (%s): 0x%llx, by hand 0x%llx",
                     (unsigned)WORDS[i].offset, WORDS[i].what, (unsigned long long)got,
                     (unsigned long long)WORDS[i].value);
        }
    }
    CHECK_TRUE(SUITE, "vic: the passthrough job's structure holds the words vic40.h's layout gives",
               CHECK_NONE, wrong == 0u, "%u words differ; first %s", (unsigned)wrong, first);

    uint32_t differs = 0;
    const char *name = "";
    for (size_t i = 0; i < VicCaseCount(); ++i) {
        const VicCase *const c = VicCaseAt(i);
        uint32_t hash = VIC_HASH_START;
        for (uint32_t j = 0; j < c->job_count; ++j) {
            VicPack(&c->jobs[j], config);
            hash = VicHash(hash, config, sizeof(config));
        }
        if (i >= sizeof(PINNED) / sizeof(PINNED[0]) || strcmp(PINNED[i].name, c->name) != 0 ||
            PINNED[i].config != hash) {
            if (differs++ == 0u) {
                name = c->name;
            }
        }
    }
    CHECK_TRUE(SUITE, "vic: every case packs the structures tools/vic-expect.py packs", CHECK_NONE,
               differs == 0u && VicCaseCount() == sizeof(PINNED) / sizeof(PINNED[0]),
               "%u of %u cases differ, first %s", (unsigned)differs, (unsigned)VicCaseCount(),
               name);
}

static uint32_t CommandHash(uint32_t slots, bool nv12) {
    uint32_t words[64];
    const size_t n = VicCommands(words, 64u, &FAKE, slots, nv12, FAKE_SYNCPT);
    uint8_t bytes[sizeof(words)];
    for (size_t i = 0; i < n; ++i) {
        for (uint32_t b = 0; b < 4u; ++b) {
            bytes[i * 4u + b] = (uint8_t)(words[i] >> (8u * b));
        }
    }
    return VicHash(VIC_HASH_START, bytes, n * 4u);
}

static void CheckCommands(void) {
    uint32_t words[64];
    const size_t n = VicCommands(words, 64u, &FAKE, 1u, false, FAKE_SYNCPT);
    const size_t want = sizeof(COMMANDS_ONE_SLOT) / sizeof(COMMANDS_ONE_SLOT[0]);
    size_t at = 0;
    while (at < n && at < want && words[at] == COMMANDS_ONE_SLOT[at]) {
        ++at;
    }
    CHECK_TRUE(SUITE, "vic: a one-slot job's command words are tools/vic-expect.py's", CHECK_NONE,
               n == want && at == want, "%u words, the script's %u; first difference at word %u",
               (unsigned)n, (unsigned)want, (unsigned)at);
    const uint32_t two = CommandHash(2u, false), nv12 = CommandHash(1u, true);
    uint32_t tiny[8];
    CHECK_TRUE(SUITE, "vic: two slots and an NV12 output add their methods as the script does",
               CHECK_NONE,
               two == COMMANDS_TWO_SLOTS_HASH && nv12 == COMMANDS_NV12_OUT_HASH &&
                   VicCommands(tiny, 8u, &FAKE, 1u, false, FAKE_SYNCPT) == 0u,
               "two slots 0x%08x (0x%08x), NV12 0x%08x (0x%08x), or a short buffer was not refused",
               two, COMMANDS_TWO_SLOTS_HASH, nv12, COMMANDS_NV12_OUT_HASH);
}

static void CheckModel(void) {
    for (size_t i = 0; i < VicCaseCount(); ++i) {
        const VicCase *const c = VicCaseAt(i);
        const VicPinned *const pin = i < sizeof(PINNED) / sizeof(PINNED[0]) ? &PINNED[i] : NULL;
        const uint32_t count = VicCaseCombinations(c);
        uint32_t wrong = 0, first = 0;
        for (uint32_t k = 0; k < count; ++k) {
            uint32_t hash = VIC_HASH_START;
            for (uint32_t j = 0; j < c->job_count; ++j) {
                VicModel(&c->jobs[j], VicCaseRules(c, k), out);
                hash = VicHash(hash, out, VicOutputSize(&c->jobs[j]));
            }
            if (pin == NULL || k >= pin->count || pin->expected[k] != hash) {
                if (wrong++ == 0u) {
                    first = k;
                }
            }
        }
        char name[96];
        snprintf(name, sizeof(name), "vic: %s expects what the script expects", c->name);
        CHECK_TRUE(SUITE, name, CHECK_NONE,
                   pin != NULL && strcmp(pin->name, c->name) == 0 && pin->count == count &&
                       wrong == 0u,
                   "%u of %u combinations of answers differ, first combination %u", (unsigned)wrong,
                   (unsigned)count, (unsigned)first);
    }
}

static uint8_t judged[VIC_JOBS_MAX][VIC_OUTPUT_MAX];
static uint8_t scratch[VIC_JOBS_MAX][VIC_OUTPUT_MAX];

/// What a case's model leaves under combination @p k, as if the engine had left it.
static void Machine(const VicCase *c, uint32_t k) {
    for (uint32_t j = 0; j < c->job_count; ++j) {
        memset(judged[j], VIC_FILL, VIC_OUTPUT_MAX);
        VicModel(&c->jobs[j], VicCaseRules(c, k), judged[j]);
    }
}

static const VicCase *Named(const char *name) {
    for (size_t i = 0; i < VicCaseCount(); ++i) {
        if (strcmp(VicCaseAt(i)->name, name) == 0) {
            return VicCaseAt(i);
        }
    }
    return VicCaseAt(0);
}

static void Judge(const VicCase *c, VicVerdict *verdict, char *detail, size_t detail_size) {
    VicJudge(c, (const uint8_t(*)[VIC_OUTPUT_MAX])judged, scratch, verdict);
    VicDetail(c, verdict, (const uint8_t(*)[VIC_OUTPUT_MAX])judged,
              (const uint8_t(*)[VIC_OUTPUT_MAX])scratch, detail, detail_size);
}

// The console's half of the family judges what the engine left with these, so they are held
// here to outputs made to order: each case's own model, nothing written, one byte off.
static void CheckJudge(void) {
    VicVerdict verdict;
    char detail[400];
    uint32_t refused = 0;
    const char *first = "none";
    for (size_t i = 0; i < VicCaseCount(); ++i) {
        const VicCase *const c = VicCaseAt(i);
        for (uint32_t k = 0; k < VicCaseCombinations(c); ++k) {
            Machine(c, k);
            Judge(c, &verdict, detail, sizeof(detail));
            if ((!verdict.passed || ((verdict.fits >> k) & 1u) == 0u) && refused++ == 0u) {
                first = c->name;
            }
        }
    }
    CHECK_TRUE(SUITE, "vic: the judge passes each case's own model under each of its answers",
               CHECK_NONE, refused == 0u, "%u refused, the first in %s", (unsigned)refused,
               first);

    const VicCase *const passthrough = Named("vic_passthrough");
    const VicCase *const nv12 = Named("vic_nv12_out");
    const VicCase *const shift = Named("vic_matrix_shift");
    Machine(passthrough, 1u);
    char swapped[96];
    Judge(passthrough, &verdict, swapped, sizeof(swapped));
    Machine(nv12, 0u);
    char plain[96];
    Judge(nv12, &verdict, plain, sizeof(plain));
    Machine(shift, 0u); // Q9 cannot tell its two answers apart here
    char either[96];
    Judge(shift, &verdict, either, sizeof(either));
    CHECK_TRUE(SUITE, "vic: a pass says which answers fit, and either where both do", CHECK_NONE,
               strcmp(swapped, "fits Q11 B") == 0 && plain[0] == '\0' &&
                   strcmp(either, "fits Q3 A, Q9 either") == 0,
               "\"%s\", \"%s\", \"%s\"", swapped, plain, either);

    for (uint32_t j = 0; j < VIC_JOBS_MAX; ++j) {
        memset(judged[j], VIC_FILL, VIC_OUTPUT_MAX);
    }
    Judge(passthrough, &verdict, detail, sizeof(detail));
    static const char NOTHING[] = "nothing was written, every byte is still 0xEE; ";
    const bool untouched = !verdict.passed && verdict.untouched &&
                           strncmp(detail, NOTHING, sizeof(NOTHING) - 1u) == 0;
    Machine(passthrough, 0u);
    judged[0][3u * VIC_RGBA_PITCH + 5u * 4u + 1u] ^= 0x01u;
    char one[400];
    Judge(passthrough, &verdict, one, sizeof(one));
    const bool named = !verdict.passed && !verdict.untouched && verdict.wrong == 1u &&
                       verdict.job == 0u && verdict.at == 3u * VIC_RGBA_PITCH + 21u &&
                       strstr(one, "1 bytes wrong under the closest answers (Q11 A), first in job "
                                   "1 at byte 3093 (row 3, byte 21 of it): 0x5b, expected 0x5a") !=
                           NULL;
    CHECK_TRUE(SUITE, "vic: a failure names the first wrong byte, or that nothing was written",
               CHECK_NONE, untouched && named, "untouched \"%.80s\"; one byte off \"%.200s\"",
               detail, one);

    uint8_t settled[VIC_QUESTIONS] = {0};
    char said[160];
    VicSettled(settled, said, sizeof(said));
    const bool nothing = said[0] == '\0';
    VicSettle(passthrough, 1u, settled);                    // Q11 A
    VicSettle(Named("vic_chroma_order"), 0xFu, settled);    // every answer fits: settles nothing
    VicSettle(Named("vic_background"), 2u, settled);        // Q7 B
    VicSettled(settled, said, sizeof(said));
    const bool agreed = strcmp(said, "Q7 B, Q11 A") == 0;
    VicSettle(Named("vic_source_crop"), 1u, settled);       // Q7 A, Q11 A
    VicSettled(settled, said, sizeof(said));
    CHECK_TRUE(SUITE, "vic: the run's note adds up the answers and names a disagreement",
               CHECK_NONE,
               nothing && agreed && strcmp(said, "Q7 A and B, cases disagree, Q11 A") == 0,
               "\"%s\"", said);
}

void RunReferenceVic(void) {
    CheckMatrix();
    CheckStructure();
    CheckCommands();
    CheckModel();
    CheckJudge();
}
